/**
 * AWS Lambda Function: HTML Room Generator
 * 
 * Accepts JSON payload with room title and stages
 * Returns HTML string with title and stage list
 */

/**
 * Escape HTML special characters to prevent XSS
 */
function escapeHtml(text) {
  const map = {
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  };
  return text.replace(/[&<>"']/g, (char) => map[char]);
}

/**
 * Generate HTML from room data
 */
function generateRoomHTML(title, stages = []) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(title)}</title>
  <style>
    * {
      margin: 0;
      padding: 0;
      box-sizing: border-box;
    }
    
    body {
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
      background: linear-gradient(135deg, #667eea 0%, #764ba2 100%);
      min-height: 100vh;
      padding: 20px;
      color: #333;
    }
    
    .container {
      max-width: 800px;
      margin: 40px auto;
      background: white;
      border-radius: 16px;
      box-shadow: 0 20px 60px rgba(0, 0, 0, 0.3);
      padding: 40px;
    }
    
    h1 {
      font-size: 2.5rem;
      color: #667eea;
      margin-bottom: 10px;
      text-align: center;
    }
    
    .subtitle {
      text-align: center;
      color: #666;
      margin-bottom: 30px;
    }
    
    .stages-title {
      font-size: 1.5rem;
      margin: 30px 0 20px;
      color: #333;
    }
    
    .stage-list {
      list-style: none;
    }
    
    .stage-item {
      background: #f7fafc;
      border-left: 4px solid #667eea;
      padding: 16px 20px;
      margin-bottom: 12px;
      border-radius: 8px;
      transition: all 0.3s ease;
    }
    
    .stage-item:hover {
      background: #edf2f7;
      transform: translateX(4px);
    }
    
    .stage-order {
      display: inline-block;
      background: #667eea;
      color: white;
      width: 32px;
      height: 32px;
      line-height: 32px;
      text-align: center;
      border-radius: 50%;
      margin-right: 12px;
      font-weight: bold;
    }
    
    .stage-label {
      font-size: 1.1rem;
      color: #2d3748;
    }
    
    .no-stages {
      text-align: center;
      color: #a0aec0;
      padding: 40px;
      font-style: italic;
    }
    
    .footer {
      margin-top: 40px;
      text-align: center;
      color: #a0aec0;
      font-size: 0.9rem;
    }
    
    @media (max-width: 768px) {
      .container {
        padding: 20px;
      }
      
      h1 {
        font-size: 2rem;
      }
    }
  </style>
</head>
<body>
  <div class="container">
    <h1>${escapeHtml(title)}</h1>
    <p class="subtitle">Escape Room Challenge</p>
    
    ${
      stages.length > 0
        ? `
    <h2 class="stages-title">Stages (${stages.length})</h2>
    <ul class="stage-list">
      ${stages
        .sort((a, b) => a.order - b.order)
        .map(
          (stage) => `
      <li class="stage-item">
        <span class="stage-order">${stage.order + 1}</span>
        <span class="stage-label">${escapeHtml(stage.label)}</span>
      </li>
      `
        )
        .join("")}
    </ul>
    `
        : `
    <div class="no-stages">
      <p>No stages defined yet.</p>
    </div>
    `
    }
    
    <div class="footer">
      <p>Generated by AWS Lambda • ${new Date().toLocaleString()}</p>
    </div>
  </div>
</body>
</html>`;
}

/**
 * Lambda Handler
 */
export const handler = async (event) => {
  console.log("Received event:", JSON.stringify(event, null, 2));

  try {
    // Parse request body
    let body;
    if (typeof event.body === "string") {
      body = JSON.parse(event.body);
    } else {
      body = event.body || {};
    }

    // Validate required fields
    if (!body.title) {
      return {
        statusCode: 400,
        headers: {
          "Content-Type": "application/json",
          "Access-Control-Allow-Origin": "*",
        },
        body: JSON.stringify({
          error: "Missing required field: title",
        }),
      };
    }

    // Extract data
    const { title, stages = [] } = body;

    // Validate stages format
    if (!Array.isArray(stages)) {
      return {
        statusCode: 400,
        headers: {
          "Content-Type": "application/json",
          "Access-Control-Allow-Origin": "*",
        },
        body: JSON.stringify({
          error: "stages must be an array",
        }),
      };
    }

    // Generate HTML
    const html = generateRoomHTML(title, stages);

    // Return HTML response
    return {
      statusCode: 200,
      headers: {
        "Content-Type": "text/html",
        "Access-Control-Allow-Origin": "*",
        "Cache-Control": "public, max-age=300",
      },
      body: html,
    };
  } catch (error) {
    console.error("Error:", error);

    return {
      statusCode: 500,
      headers: {
        "Content-Type": "application/json",
        "Access-Control-Allow-Origin": "*",
      },
      body: JSON.stringify({
        error: "Internal server error",
        message: error.message,
      }),
    };
  }
};
